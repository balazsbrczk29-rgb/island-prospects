// Usage: node factory/tools/readme.mjs  -> rewrites the "All sites" table in README.md from prospects.json + factory/status/*.json
import fs from 'node:fs'; import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'factory/config.json'), 'utf8'));
const P = JSON.parse(fs.readFileSync(path.join(root, 'factory/data/prospects.json'), 'utf8'));
const st = s => { try { return JSON.parse(fs.readFileSync(path.join(root, 'factory/status', s + '.json'), 'utf8')); } catch { return null; } };
const rows = P.map(p => ({ p, s: st(p.slug) }));
const label = s => !s ? 'not built' : s.state === 'skipped' ? 'skipped' : s.jobspec_built ? 'upgraded' : s.state === 'building' ? 'building now' : 'older version';
const order = { upgraded: 0, 'building now': 1, 'older version': 2, 'not built': 3, skipped: 4 };
rows.sort((a, b) => order[label(a.s)] - order[label(b.s)] || a.p.name.localeCompare(b.p.name));
const n = k => rows.filter(r => label(r.s) === k).length;
const live = s => s && s.state !== 'skipped' && fs.existsSync(path.join(root, s.slug || '', 'index.html'));
let t = `## All sites (auto-generated by \`factory/tools/readme.mjs\`, ${new Date().toISOString().slice(0, 10)})\n\n`;
t += `**${n('upgraded')} upgraded** to the latest standard (job spec + design.md) · ${n('building now')} building now · ${n('older version')} older version · ${n('not built')} not built · ${n('skipped')} skipped. Live dashboard: ${cfg.pages_base}\n\n`;
t += `| Business | Niche | Status | New concept site | Their current site |\n|---|---|---|---|---|\n`;
for (const { p, s } of rows) {
  const url = cfg.pages_base + p.slug + '/';
  const has = fs.existsSync(path.join(root, p.slug, 'index.html')) && (!s || s.state !== 'skipped');
  t += `| ${p.name.replace(/\|/g, '/')} | ${p.niche} | ${label(s)} | ${has ? `[open](${url})` : '-'} | ${p.current_site ? `[${p.current_site}](https://${p.current_site})` : 'none'} |\n`;
}
const f = path.join(root, 'README.md'); let r = fs.readFileSync(f, 'utf8');
const start = r.indexOf('## All sites'); if (start >= 0) { const end = r.indexOf('\n## ', start + 5); r = r.slice(0, start) + (end >= 0 ? r.slice(end + 1) : ''); }
r = r.trimEnd() + '\n\n' + t;
fs.writeFileSync(f, r);
console.log(`README updated: ${n('upgraded')} upgraded, ${n('older version')} older, ${n('not built')} not built, ${n('skipped')} skipped`);
